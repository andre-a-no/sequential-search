"""Adapter: sequential-analysis Procedure -> Node + EvidenceState (ADR-003, layer 2).

This is the only place in the kernel that knows about the upstream package. The
adapter is thin: it does not implement statistics, it wires the node contract to
the Run contract.

The degenerate-anchor invariant requires numerical agreement with a standalone
run, so `ProcedureNode` must use exactly one `Run` per node and pass
observations through untransformed (see Observation in graph/node.py).
"""
from __future__ import annotations

from typing import Any

from sequential_search.graph.edge import Decision, EvidenceState
from sequential_search.graph.node import Observation


class ProcedureNode:
    """An experiment node over a sequential-analysis sequential procedure.

    Implements the graph.node.Node protocol. Constructed lazily: the Run itself
    is created on the first step, so importing the kernel does not require the
    heavy upstream package.
    """

    def __init__(self, name: str, procedure_factory, *, seed: int | None = None,
                 cost_per_step: float = 1.0, canonical_key: str | None = None) -> None:
        self.name = name
        self._procedure_factory = procedure_factory   # callable() -> Procedure
        self._seed = seed
        self._cost = float(cost_per_step)
        self._canonical_key = canonical_key
        self._run = None
        self._t = 0
        self._last_output: Any = None
        self._last_values: dict[str, Any] = {}

    # --- Node protocol ---------------------------------------------------
    def step(self) -> Observation:
        """Sync the counter and return the last accepted observation.

        For ProcedureNode data arrives from outside via feed(), so step()
        exists for compatibility with the Node protocol (e.g. nodes that
        generate their own observations) and does not advance the statistics.
        """
        return Observation(t=self._t, values=dict(self._last_values))

    def feed(self, values: dict[str, Any]) -> EvidenceState:
        """Hand an observation to the procedure, return the edge's accumulated evidence.

        This is the main path: Traversal calls it instead of a "blind" step(),
        because data comes from outside (a tomography slice, an agent's action,
        an inference step) rather than being generated by the node.
        """
        run = self._ensure_run()
        event = run.step(values)
        self._t = event.t
        self._last_values = dict(values)
        self._last_output = event.output
        return self.evidence()

    def state(self) -> Any:
        return self._ensure_run().state

    def cost(self) -> float:
        return self._cost

    def canonical_key(self) -> str:
        return self._canonical_key or f"{self.name}@{self._t}"

    def is_terminal(self) -> bool:
        return self._run is not None and self._run.terminal

    # --- evidence ----------------------------------------------------------
    def evidence(self) -> EvidenceState:
        """e-value derived from the procedure's log LR (for SPRT/martingale procedures)."""
        out = self._last_output
        if out is None:
            return EvidenceState(e=1.0, stat=None, n=0)
        llr = getattr(out, "llr", None)
        stat = llr if llr is not None else getattr(out, "stat", None)
        e = _exp_if_finite(llr) if llr is not None else 1.0
        n = int(getattr(out, "n", self._t))
        return EvidenceState(e=e, stat=out, n=n)

    def decision(self) -> Decision:
        d = getattr(self._last_output, "decision", None)
        if d in ("reject_h0", "accept_h1"):
            return Decision.ACCEPT
        if d in ("accept_h0", "reject_h1"):
            return Decision.REJECT
        return Decision.PENDING

    # --- internals ---------------------------------------------------------
    def _ensure_run(self):
        if self._run is None:
            from sequential_analysis import Run  # local import: [full] extra absent -> no upstream
            proc = self._procedure_factory()
            self._run = Run(proc, seed=self._seed)
            self._run.start()
        return self._run


def _exp_if_finite(x: float | None) -> float:
    """log LR -> e-value with overflow protection (the kernel's e-currency)."""
    import math

    if x is None:
        return 1.0
    if x > 700:
        return math.inf
    if x < -745:
        return 0.0
    return math.exp(x)


def wald_thresholds(alpha: float, beta: float) -> tuple[float, float]:
    """Wald boundaries in e-currency for the degenerate case (SPRT).

    upper = exp(log((1-beta)/alpha)) -- threshold for rejecting H0;
    lower = exp(log(beta/(1-alpha))) -- threshold for accepting H0.

    Returns exponentials precisely because EvidenceState.e stores an e-value,
    not a log LR; agreement with `SPRT.upper/lower` from sequential-analysis is
    checked by the degenerate-anchor test.
    """
    import math

    if not (0 < alpha < 1 and 0 < beta < 1 and alpha + beta < 1):
        raise ValueError("need alpha, beta in (0,1) with alpha + beta < 1")
    return math.exp(math.log((1.0 - beta) / alpha)), math.exp(math.log(beta / (1.0 - alpha)))
